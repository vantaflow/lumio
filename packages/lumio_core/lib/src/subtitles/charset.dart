import 'dart:convert';

/// Levée quand les octets ne ressemblent pas à un fichier texte de sous-titres
/// (image, archive, contenu binaire).
class SubtitleDecodeException implements Exception {
  const SubtitleDecodeException(this.message);
  final String message;

  @override
  String toString() => 'SubtitleDecodeException: $message';
}

/// Décode un fichier de sous-titres vers une chaîne.
///
/// Ordre : rejet des binaires (PNG/ZIP/JPEG, octets NUL), BOM UTF-8 puis
/// UTF-16 LE/BE, UTF-8 strict, Windows-1256 si les octets arabes dominent,
/// sinon Windows-1252.
String decodeSubtitleBytes(List<int> bytes) {
  if (_hasBinaryMagic(bytes)) {
    throw const SubtitleDecodeException('Le fichier n\'est pas un texte.');
  }
  if (bytes.length >= 3 &&
      bytes[0] == 0xEF &&
      bytes[1] == 0xBB &&
      bytes[2] == 0xBF) {
    return utf8.decode(bytes.sublist(3), allowMalformed: true);
  }
  if (bytes.length >= 2 && bytes[0] == 0xFF && bytes[1] == 0xFE) {
    return _utf16(bytes, 2, littleEndian: true);
  }
  if (bytes.length >= 2 && bytes[0] == 0xFE && bytes[1] == 0xFF) {
    return _utf16(bytes, 2, littleEndian: false);
  }
  if (bytes.contains(0)) {
    throw const SubtitleDecodeException('Le fichier est binaire.');
  }
  try {
    return const Utf8Decoder(allowMalformed: false).convert(bytes);
  } on FormatException {
    // Pas de l'UTF-8 : repli sur un codage historique.
  }
  var high = 0;
  var arabic = 0;
  for (final b in bytes) {
    if (b >= 0x80) {
      high++;
      if (_isArabic1256(b)) arabic++;
    }
  }
  final table = (high > 0 && arabic * 2 > high) ? _cp1256 : _cp1252;
  return _single(bytes, table);
}

bool _hasBinaryMagic(List<int> b) {
  bool starts(List<int> m) {
    if (b.length < m.length) return false;
    for (var i = 0; i < m.length; i++) {
      if (b[i] != m[i]) return false;
    }
    return true;
  }

  return starts(const [0x89, 0x50, 0x4E, 0x47]) || // PNG
      starts(const [0x50, 0x4B, 0x03, 0x04]) || // ZIP
      starts(const [0x50, 0x4B, 0x05, 0x06]) || // ZIP vide
      starts(const [0xFF, 0xD8, 0xFF]); // JPEG
}

bool _isArabic1256(int b) {
  final cp = _cp1256[b - 0x80];
  return cp >= 0x0600 && cp <= 0x06FF && cp != 0x066A;
}

String _single(List<int> bytes, List<int> table) {
  final out = StringBuffer();
  for (final b in bytes) {
    out.writeCharCode(b < 0x80 ? b : table[b - 0x80]);
  }
  return out.toString();
}

String _utf16(List<int> bytes, int start, {required bool littleEndian}) {
  final units = <int>[];
  for (var i = start; i + 1 < bytes.length; i += 2) {
    units.add(
      littleEndian
          ? bytes[i] | (bytes[i + 1] << 8)
          : (bytes[i] << 8) | bytes[i + 1],
    );
  }
  return String.fromCharCodes(units);
}

